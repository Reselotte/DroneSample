const ITEMS = Object.fromEntries(CHECKLIST_GROUPS.flatMap((g) => g.items.map((it) => [it.key, it])));

/**
 * แปลงข้อมูลจากฐานข้อมูล { key: "รายละเอียด" } → รายการจุดเด่นเรียงตามเช็กลิสต์
 * [{ key, label, note }] (ข้าม key ที่ไม่มีในเช็กลิสต์แล้ว)
 */
export function highlightList(map) {
  if (!map || typeof map !== "object") return [];
  return CHECKLIST_GROUPS.flatMap((g) => g.items)
    .filter((it) => Object.prototype.hasOwnProperty.call(map, it.key))
    .map((it) => ({ key: it.key, label: it.label, note: String(map[it.key] || "").trim() }));
}

export const checklistItem = (key) => ITEMS[key];

